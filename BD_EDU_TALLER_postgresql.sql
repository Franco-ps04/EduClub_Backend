CREATE DATABASE EduTaller;

-- ============================================================
-- 1. USUARIO
-- ============================================================

CREATE TABLE Usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    contrasena VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'alumno',
    telefono VARCHAR(9) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_modificacion TIMESTAMP,

    CONSTRAINT chk_usuario_rol
        CHECK (rol IN ('alumno', 'docente', 'administrador')),

    CONSTRAINT chk_usuario_telefono
        CHECK (telefono ~ '^[0-9]{9}$')
);

-- ============================================================
-- 2. ALUMNO
-- ============================================================

CREATE TABLE Alumno (
    id_usuario INTEGER PRIMARY KEY,

    CONSTRAINT fk_alumno_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES Usuario(id_usuario)
        ON DELETE CASCADE
);

-- ============================================================
-- 3. DOCENTE
-- ============================================================

CREATE TABLE Docente (
    id_docente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institucion VARCHAR(150) NOT NULL,
    id_usuario INTEGER NOT NULL UNIQUE,

    CONSTRAINT fk_docente_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES Usuario(id_usuario)
        ON DELETE CASCADE
);

-- ============================================================
-- 4. ADMINISTRADOR
-- ============================================================

CREATE TABLE Administrador (
    id_usuario INTEGER PRIMARY KEY,

    CONSTRAINT fk_administrador_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES Usuario(id_usuario)
        ON DELETE CASCADE
);

-- ============================================================
-- 5. CARGA MASIVA DE ALUMNOS
-- ============================================================

CREATE TABLE CargaAlumno (
    id_carga INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_archivo VARCHAR(255) NOT NULL,
    fecha_carga TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',

    CONSTRAINT chk_carga_alumno_estado
        CHECK (
            estado IN (
                'pendiente',
                'procesando',
                'procesado',
                'error'
            )
        )
);

-- ============================================================
-- 6. DETALLE DE CARGA DE ALUMNOS
-- ============================================================

CREATE TABLE DetalleCargaAlumno (
    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carga INTEGER NOT NULL,
    id_usuario INTEGER NULL,

    nombre VARCHAR(150),
    correo VARCHAR(150),
    telefono VARCHAR(9),
    contrasena VARCHAR(255),

    estado VARCHAR(50) NOT NULL,

    CONSTRAINT fk_detalle_carga
        FOREIGN KEY (id_carga)
        REFERENCES CargaAlumno(id_carga)
        ON DELETE CASCADE,

    CONSTRAINT fk_detalle_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES Usuario(id_usuario)
        ON DELETE SET NULL,

    CONSTRAINT chk_detalle_carga_estado
        CHECK (
            estado IN (
                'valido_para_registrar',
                'correo_existente',
                'datos_incompletos_o_invalidos',
                'correo_duplicado_excel',
                'creado_exitosamente'
            )
        )
);

-- ============================================================
-- 7. TIPO DE EVENTO
-- ============================================================

CREATE TABLE TipoEvento (
    id_tipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);

-- ============================================================
-- 8. TIPO DE AREA
-- ============================================================

CREATE TABLE TipoArea (
    id_area INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);

-- ============================================================
-- 9. TALLER
-- ============================================================

CREATE TABLE Taller (
    id_taller INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    ubicacion VARCHAR(255) NOT NULL,
    capacidad INTEGER NOT NULL DEFAULT 30,
    inscritos INTEGER NOT NULL DEFAULT 0,
    modalidad VARCHAR(30) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    archivado BOOLEAN NOT NULL DEFAULT FALSE,
    latitud NUMERIC(10,7),
    longitud NUMERIC(10,7),
    institucion VARCHAR(150) NOT NULL,
    imagen_url VARCHAR(500),
    id_area INTEGER NOT NULL,
    id_tipo INTEGER NOT NULL,
    id_docente INTEGER NOT NULL,

    CONSTRAINT fk_taller_area
        FOREIGN KEY (id_area)
        REFERENCES TipoArea(id_area)
        ON DELETE RESTRICT,

    CONSTRAINT fk_taller_tipo
        FOREIGN KEY (id_tipo)
        REFERENCES TipoEvento(id_tipo)
        ON DELETE RESTRICT,

    CONSTRAINT fk_taller_docente
        FOREIGN KEY (id_docente)
        REFERENCES Docente(id_docente)
        ON DELETE RESTRICT,

    CONSTRAINT chk_taller_capacidad
        CHECK (capacidad > 0 AND capacidad <= 30),

    CONSTRAINT chk_taller_inscritos
        CHECK (inscritos >= 0 AND inscritos <= capacidad),

    CONSTRAINT chk_taller_latitud
        CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90),

    CONSTRAINT chk_taller_longitud
        CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180)
);

