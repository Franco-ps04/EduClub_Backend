-- ============================================================
-- FUNCION: VALIDAR CANTIDAD MAXIMA DE SESIONES
-- Sesion: maximo 3
-- Seminario: maximo 1
-- ============================================================

CREATE OR REPLACE FUNCTION fn_validar_cantidad_sesiones()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_tipo VARCHAR(50);
    v_taller INTEGER;
    v_cantidad INTEGER;
BEGIN
    v_taller := COALESCE(NEW.id_taller, OLD.id_taller);

    SELECT te.nombre
    INTO v_tipo
    FROM Taller t
    INNER JOIN TipoEvento te
        ON te.id_tipo = t.id_tipo
    WHERE t.id_taller = v_taller;

    SELECT COUNT(*)
    INTO v_cantidad
    FROM Sesion
    WHERE id_taller = v_taller;

    IF LOWER(v_tipo) IN ('sesion', 'sesión') AND v_cantidad > 3 THEN
        RAISE EXCEPTION
            'Un taller de tipo Sesión no puede tener más de 3 sesiones.';
    ELSIF LOWER(v_tipo) = 'seminario' AND v_cantidad > 1 THEN
        RAISE EXCEPTION
            'Un Seminario solo puede tener 1 sesión.';
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_validar_cantidad_sesiones
AFTER INSERT OR UPDATE OR DELETE ON Sesion
FOR EACH ROW
EXECUTE FUNCTION fn_validar_cantidad_sesiones();

-- ============================================================
-- FUNCION: PROCESAR ASISTENCIA
-- ============================================================

CREATE OR REPLACE FUNCTION fn_procesar_asistencia()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_id_inscripcion INTEGER;
    v_id_alumno INTEGER;
    v_id_taller INTEGER;

    v_total_sesiones INTEGER;
    v_total_registradas INTEGER;
    v_total_asistidas INTEGER;

    v_porcentaje NUMERIC(5,2);
    v_total_asistencias_alumno INTEGER;

    r RECORD;
BEGIN
    v_id_inscripcion := COALESCE(NEW.id_inscripcion, OLD.id_inscripcion);

    SELECT i.id_alumno, i.id_taller
    INTO v_id_alumno, v_id_taller
    FROM Inscripcion i
    WHERE i.id_inscripcion = v_id_inscripcion;

    -- ========================================================
    -- ASISTENCIAS ACUMULADAS DEL ALUMNO
    -- ========================================================

    SELECT COUNT(*)
    INTO v_total_asistencias_alumno
    FROM Asistencia a
    INNER JOIN Inscripcion i
        ON i.id_inscripcion = a.id_inscripcion
    WHERE i.id_alumno = v_id_alumno
      AND a.asistio = TRUE;

    FOR r IN
        SELECT *
        FROM ReglaReconocimiento rr
        WHERE rr.activo = TRUE
          AND rr.tipo = 'ASISTENCIA_ACUMULADA'
          AND rr.umbral <= v_total_asistencias_alumno
    LOOP
        INSERT INTO Reconocimiento (
            id_alumno,
            id_regla,
            id_taller,
            fecha_emision
        )
        VALUES (
            v_id_alumno,
            r.id_regla,
            NULL,
            CURRENT_DATE
        )
        ON CONFLICT DO NOTHING;
    END LOOP;

    -- ========================================================
    -- SESIONES DEL TALLER
    -- ========================================================

    SELECT COUNT(*)
    INTO v_total_sesiones
    FROM Sesion s
    WHERE s.id_taller = v_id_taller;

    IF v_total_sesiones = 0 THEN
        RETURN COALESCE(NEW, OLD);
    END IF;

    -- ========================================================
    -- SESIONES REGISTRADAS PARA LA INSCRIPCION
    -- ========================================================

    SELECT
        COUNT(*),
        COUNT(*) FILTER (WHERE a.asistio = TRUE)
    INTO
        v_total_registradas,
        v_total_asistidas
    FROM Asistencia a
    INNER JOIN Sesion s
        ON s.id_sesion = a.id_sesion
    WHERE a.id_inscripcion = v_id_inscripcion
      AND s.id_taller = v_id_taller;

    IF v_total_registradas = v_total_sesiones THEN

        v_porcentaje := ROUND(
            (v_total_asistidas::NUMERIC / v_total_sesiones::NUMERIC) * 100,
            2
        );

        -- ====================================================
        -- DIPLOMA SEGUN REGLA
        -- ====================================================

        SELECT *
        INTO r
        FROM ReglaDiploma rd
        WHERE rd.activo = TRUE
          AND v_porcentaje BETWEEN
              rd.porcentaje_minimo
              AND rd.porcentaje_maximo
        ORDER BY rd.porcentaje_minimo DESC
        LIMIT 1;

        IF FOUND THEN
            INSERT INTO Diploma (
                id_alumno,
                id_taller,
                id_regla_diploma,
                nombre_nivel,
                descripcion,
                porcentaje_minimo,
                porcentaje_maximo,
                porcentaje_obtenido,
                fecha_emision
            )
            VALUES (
                v_id_alumno,
                v_id_taller,
                r.id_regla_diploma,
                r.nombre_nivel,
                r.descripcion,
                r.porcentaje_minimo,
                r.porcentaje_maximo,
                v_porcentaje,
                CURRENT_DATE
            )
            ON CONFLICT (id_alumno, id_taller)
            DO NOTHING;
        END IF;

        -- ====================================================
        -- RECONOCIMIENTO POR 100% DEL TALLER
        -- ====================================================

        IF v_porcentaje = 100 THEN
            FOR r IN
                SELECT *
                FROM ReglaReconocimiento rr
                WHERE rr.activo = TRUE
                  AND rr.tipo = 'TALLER_COMPLETADO'
                  AND rr.umbral = 100
            LOOP
                INSERT INTO Reconocimiento (
                    id_alumno,
                    id_regla,
                    id_taller,
                    fecha_emision
                )
                VALUES (
                    v_id_alumno,
                    r.id_regla,
                    v_id_taller,
                    CURRENT_DATE
                )
                ON CONFLICT DO NOTHING;
            END LOOP;
        END IF;

    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_procesar_asistencia
AFTER INSERT OR UPDATE OR DELETE ON Asistencia
FOR EACH ROW
EXECUTE FUNCTION fn_procesar_asistencia();

-- ============================================================
-- FUNCION: MARCAR MENSAJE COMO RESPONDIDO
-- ============================================================

CREATE OR REPLACE FUNCTION fn_marcar_mensaje_respondido()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE Mensaje
    SET respondido = TRUE
    WHERE id_mensaje = NEW.id_mensaje;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_mensaje_respondido
AFTER INSERT ON RespuestaMensaje
FOR EACH ROW
EXECUTE FUNCTION fn_marcar_mensaje_respondido();

